import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import test from 'node:test'

const read = relativePath => fs.readFileSync(path.resolve(relativePath), 'utf8')
const types = read('src/types.ts')
const api = read('src/api/AgentServerClient.ts')
const capability = read('src/lib/claude-mcp.ts')
const composer = read('src/components/Composer.tsx')
const chat = read('src/components/ChatScreen.tsx')
const shell = read('src/components/AppShell.tsx')
const panel = read('src/components/ClaudeMcpDialog.tsx')

test('mobile uses the versioned, secret-free Claude MCP wire contract', () => {
  assert.match(types, /export interface ClaudeMcpSnapshot[\s\S]*?version: 1/)
  assert.match(types, /generation: string \| null/)
  assert.match(types, /truncated: boolean/)
  assert.match(types, /expected_generation: string/)
  assert.match(types, /'reconnect' \| 'reconnect_all' \| 'enable' \| 'disable'/)
  assert.match(types, /server_name: string \| null/)
  assert.match(types, /status: ClaudeMcpServerStatus/)
  assert.match(types, /scope: 'user' \| 'project' \| 'local' \| 'claudeai' \| 'managed' \| null/)
  assert.doesNotMatch(types.match(/export interface ClaudeMcpServer \{[\s\S]*?\n\}/)?.[0] ?? '', /command|args|env|headers|url|tools:/i)

  assert.match(api, /claudeMcp\(sessionId: string\): Promise<ClaudeMcpSnapshot>/)
  assert.match(api, /get\(`\/api\/sessions\/\$\{encodeURIComponent\(sessionId\)\}\/claude\/mcp`\)/)
  assert.match(api, /controlClaudeMcp\(sessionId: string, input: ClaudeMcpControlInput\): Promise<ClaudeMcpSnapshot>/)
  assert.match(api, /post\(`\/api\/sessions\/\$\{encodeURIComponent\(sessionId\)\}\/claude\/mcp`, input\)/)
})

test('capability gate and exact slash command fail closed', () => {
  assert.match(capability, /CLAUDE_MCP_MANAGEMENT_MIN_VERSION = 3/)
  assert.match(capability, /version < CLAUDE_MCP_MANAGEMENT_MIN_VERSION \|\| features\.mcp_management !== true/)
  assert.match(capability, /available: candidate\.available === true/)
  assert.match(capability, /\^\\\/mcp\\s\*\$\/i\.test\(text\.trim\(\)\)/)
  assert.match(panel, /MCP management needs a newer AgentsServer/)
  assert.match(panel, /does not advertise Claude MCP management/)
  assert.match(panel, /!connectionReady\n      \|\| !endpointAvailable[\s\S]*?\) return null[\s\S]*?expectedConnection\.claudeMcp\(expectedSessionId\)/)
})

test('exact /mcp opens the app panel without admitting or sending a turn', () => {
  const commandBranch = composer.indexOf('if (consumeComposer && isClaudeMcpCommand(currentDraft))')
  const admission = composer.indexOf('beginTurnAdmission(sessionId)')
  const sendPrompt = composer.indexOf('const request = sendPrompt(')
  assert.ok(commandBranch >= 0)
  assert.ok(commandBranch < admission)
  assert.ok(commandBranch < sendPrompt)
  assert.match(composer, /isClaudeMcpCommand\(currentDraft\)[\s\S]*?currentState\.sessions\.find\(candidate => candidate\.id === sessionId\)[\s\S]*?setSessionDraft\(sessionId, '', profileGeneration\)[\s\S]*?inputRef\.current\?\.clear\(\)[\s\S]*?currentSession\?\.backend === 'claude'\) onOpenMcp\(\)[\s\S]*?return/)
  assert.match(composer, /\/mcp is available in Claude chats only\./)
  assert.match(composer, /mcpCommand \? mcpCommandLabel/)
  assert.match(chat, /<Composer[\s\S]*?onOpenMcp=\{onOpenMcp\}/)
  assert.match(shell, /<ClaudeMcpDialog/)
  assert.match(shell, /mcpSessionId === selected\?\.id/)
})

test('panel fences every result to the active client, profile generation, and selected Claude chat', () => {
  assert.match(panel, /const request = \+\+requestEpoch\.current/g)
  assert.match(panel, /request === requestEpoch\.current/)
  assert.match(panel, /scopeKeyRef\.current === expectedScopeKey/)
  assert.match(panel, /client === connection/)
  assert.match(panel, /state\.activeProfileId === profileId/)
  assert.match(panel, /state\.profileGeneration === profileGeneration/)
  assert.match(panel, /state\.selectedSessionId === sessionId/)
  assert.match(panel, /session\?\.backend === 'claude'/)
  assert.match(panel, /mounted\.current = false[\s\S]*?requestEpoch\.current \+= 1/)
  assert.match(shell, /setMcpSessionId\(null\)[\s\S]*?setModalGeneration\(profileGeneration\)/)
})

