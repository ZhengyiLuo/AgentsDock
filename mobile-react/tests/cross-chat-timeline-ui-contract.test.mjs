  assert.match(projection, /event\.purpose === 'cross_chat_handoff_delivery'/)
  assert.match(projection, /const hasVisibleUserContent = Boolean\(messageText\(event\)\.trim\(\) \|\| event\.file_ids\?\.length\)/)
  assert.match(projection, /if \(!isInternalDeliveryTurn\(event\) && hasVisibleUserContent\) active\.user = event/)
